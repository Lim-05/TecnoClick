BEGIN;

-- 1. ELIMINACIÓN PREVIA (En orden inverso de dependencias para evitar conflictos)
DROP TABLE IF EXISTS auth_refresh_tokens CASCADE;
DROP TABLE IF EXISTS auth_sessions CASCADE;
DROP TABLE IF EXISTS auditoria CASCADE;
DROP TABLE IF EXISTS recuperacion_contrasena CASCADE;
DROP TABLE IF EXISTS resena CASCADE;
DROP TABLE IF EXISTS ingresos CASCADE;
DROP TABLE IF EXISTS pago_tarjeta CASCADE;
DROP TABLE IF EXISTS pago_efectivo CASCADE;
DROP TABLE IF EXISTS detalle_pedido CASCADE;
DROP TABLE IF EXISTS pedido CASCADE;
DROP TABLE IF EXISTS datos_tarjeta CASCADE;
DROP TABLE IF EXISTS productos CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS rol_permiso CASCADE;
DROP TABLE IF EXISTS permisos CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- =============================================================================
-- 2. TABLAS DE SEGURIDAD, ROLES Y PERMISOS
-- =============================================================================

CREATE TABLE public.roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    es_sistema BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT roles_codigo_valido CHECK (
        codigo = lower(btrim(codigo)) AND codigo <> ''
    ),
    CONSTRAINT roles_nombre_valido CHECK (btrim(nombre) <> '')
);

CREATE TABLE public.permisos (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL,
    CONSTRAINT permisos_codigo_valido CHECK (
        codigo = lower(btrim(codigo)) AND codigo <> ''
    )
);

CREATE TABLE public.rol_permiso (
    id_rol INTEGER NOT NULL,
    id_permiso INTEGER NOT NULL,
    PRIMARY KEY (id_rol, id_permiso),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (id_rol)
        REFERENCES public.roles (id_rol) ON DELETE CASCADE,
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (id_permiso)
        REFERENCES public.permisos (id_permiso) ON DELETE CASCADE
);

CREATE INDEX idx_rol_permiso_permiso ON public.rol_permiso (id_permiso);

-- =============================================================================
-- 3. TABLA DE USUARIOS
-- =============================================================================

CREATE TABLE public.usuario (
    id_usuario SERIAL PRIMARY KEY,
    nombre_usuario VARCHAR(100) NOT NULL,
    apellido_usuario VARCHAR(100) NOT NULL,
    telefono_usuario VARCHAR(20),
    correo_usuario VARCHAR(150) NOT NULL UNIQUE,
    direccion_usuario TEXT,
    codigo_postal VARCHAR(10) NOT NULL,
    estado_usuario VARCHAR(100) NOT NULL,
    municipio_usuario VARCHAR(100) NOT NULL,
    colonia_usuario VARCHAR(100) NOT NULL,
    referencias TEXT,
    contrasena VARCHAR(255) NOT NULL,
    id_rol INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol)
        REFERENCES public.roles (id_rol) ON DELETE RESTRICT
);

CREATE INDEX idx_usuario_id_rol ON public.usuario (id_rol);
CREATE INDEX idx_usuario_correo ON public.usuario (correo_usuario);

-- =============================================================================
-- 4. TABLA DE AUDITORÍA (INMUTABLE)
-- =============================================================================

CREATE TABLE public.auditoria (
    id_auditoria BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER,
    actor_referencia TEXT NOT NULL,
    accion VARCHAR(100) NOT NULL,
    entidad VARCHAR(100) NOT NULL,
    id_entidad TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detalle JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE SET NULL,
    CONSTRAINT auditoria_actor_valido CHECK (btrim(actor_referencia) <> ''),
    CONSTRAINT auditoria_accion_valida CHECK (btrim(accion) <> ''),
    CONSTRAINT auditoria_entidad_valida CHECK (btrim(entidad) <> '')
);

CREATE INDEX idx_auditoria_fecha ON public.auditoria (fecha DESC);
CREATE INDEX idx_auditoria_usuario_fecha ON public.auditoria (id_usuario, fecha DESC);

CREATE OR REPLACE FUNCTION public.rechazar_cambio_auditoria()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    RAISE EXCEPTION 'Los registros de auditoria son inmutables.'
        USING ERRCODE = '42501';
END;
$$;

DROP TRIGGER IF EXISTS auditoria_inmutable ON public.auditoria;
CREATE TRIGGER auditoria_inmutable
    BEFORE UPDATE OR DELETE ON public.auditoria
    FOR EACH ROW
    EXECUTE FUNCTION public.rechazar_cambio_auditoria();

-- =============================================================================
-- 5. TABLAS DE CATÁLOGO: CATEGORÍAS Y PRODUCTOS
-- =============================================================================

CREATE TABLE public.categoria (
    id_categoria SERIAL PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL,
    descripcion_categoria TEXT
);

CREATE TABLE public.productos (
    id_producto SERIAL PRIMARY KEY,
    id_categoria INTEGER,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    descripcion TEXT,
    precio NUMERIC(10, 2) NOT NULL,
    imagen VARCHAR(255),
    stock INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_productos_categoria FOREIGN KEY (id_categoria)
        REFERENCES public.categoria (id_categoria) ON DELETE SET NULL
);

CREATE INDEX idx_productos_categoria ON public.productos (id_categoria);

-- =============================================================================
-- 6. MÉTODOS DE PAGO Y TARJETAS DE USUARIO
-- =============================================================================

CREATE TABLE public.datos_tarjeta (
    id_tarjeta SERIAL PRIMARY KEY,
    nombre_titular VARCHAR(150) NOT NULL,
    numero_tarjeta VARCHAR(30) NOT NULL,
    fecha_vencimiento VARCHAR(10) NOT NULL,
    cvv VARCHAR(10) NOT NULL,
    id_usuario INTEGER NOT NULL,
    CONSTRAINT fk_tarjeta_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE
);

CREATE INDEX idx_tarjeta_usuario ON public.datos_tarjeta (id_usuario);

-- =============================================================================
-- 7. PEDIDOS, DETALLES Y PAGOS
-- =============================================================================

CREATE TABLE public.pedido (
    id_pedido SERIAL PRIMARY KEY,
    monto_pedido NUMERIC(10, 2) NOT NULL,
    fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_pedido VARCHAR(50) NOT NULL DEFAULT 'pendiente',
    id_usuario INTEGER NOT NULL,
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE
);

CREATE INDEX idx_pedido_usuario ON public.pedido (id_usuario);
CREATE INDEX idx_pedido_estado ON public.pedido (estado_pedido);

CREATE TABLE public.detalle_pedido (
    id_detalle SERIAL PRIMARY KEY,
    id_pedido INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido)
        REFERENCES public.pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES public.productos (id_producto) ON DELETE RESTRICT
);

CREATE INDEX idx_detalle_pedido ON public.detalle_pedido (id_pedido);

CREATE TABLE public.pago_efectivo (
    id_pago_efectivo SERIAL PRIMARY KEY,
    folio VARCHAR(100) NOT NULL,
    id_pedido INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    CONSTRAINT fk_pago_efectivo_pedido FOREIGN KEY (id_pedido)
        REFERENCES public.pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_pago_efectivo_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE public.pago_tarjeta (
    id_pago_tarjeta SERIAL PRIMARY KEY,
    folio VARCHAR(100) NOT NULL,
    id_pedido INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    id_tarjeta INTEGER,
    CONSTRAINT fk_pago_tarjeta_pedido FOREIGN KEY (id_pedido)
        REFERENCES public.pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_pago_tarjeta_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_pago_tarjeta_datos FOREIGN KEY (id_tarjeta)
        REFERENCES public.datos_tarjeta (id_tarjeta) ON DELETE SET NULL
);

CREATE TABLE public.ingresos (
    id_ingreso SERIAL PRIMARY KEY,
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
    id_pedido INTEGER NOT NULL,
    CONSTRAINT fk_ingresos_pedido FOREIGN KEY (id_pedido)
        REFERENCES public.pedido (id_pedido) ON DELETE CASCADE
);

CREATE INDEX idx_ingresos_pedido ON public.ingresos (id_pedido);

-- =============================================================================
-- 8. RESEÑAS Y RECUPERACIÓN DE CONTRASEÑA
-- =============================================================================

CREATE TABLE public.resena (
    id_resena SERIAL PRIMARY KEY,
    resena TEXT NOT NULL,
    id_usuario INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    CONSTRAINT fk_resena_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_resena_producto FOREIGN KEY (id_producto)
        REFERENCES public.productos (id_producto) ON DELETE CASCADE
);

CREATE INDEX idx_resena_producto ON public.resena (id_producto);

CREATE TABLE public.recuperacion_contrasena (
    id_recuperacion SERIAL PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    token VARCHAR(255) NOT NULL UNIQUE,
    expiracion TIMESTAMP NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_recuperacion_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE
);

-- =============================================================================
-- 9. GESTIÓN DE SESIONES JWT Y REFRESH TOKENS
-- =============================================================================

CREATE TABLE public.auth_sessions (
    id UUID PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_auth_sessions_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE CASCADE
);

CREATE INDEX idx_auth_sessions_user ON public.auth_sessions (id_usuario);

CREATE TABLE public.auth_refresh_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    session_id UUID NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_auth_refresh_session FOREIGN KEY (session_id)
        REFERENCES public.auth_sessions (id) ON DELETE CASCADE
);

CREATE INDEX idx_auth_refresh_session ON public.auth_refresh_tokens (session_id);

